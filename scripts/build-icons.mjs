/* 从 lucide-static 生成项目自用的 SVG sprite。
 * 只打包 scripts/lucide-icons.json 里登记的图标，避免把整库塞进页面。
 * 用法：npm run icons（生成）；npm run check:icons（校验是否漂移）。 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = path.join(ROOT, 'scripts', 'lucide-icons.json');
const SRC_DIR = path.join(ROOT, 'node_modules', 'lucide-static');
const OUT_SPRITE = path.join(ROOT, 'public', 'vendor', 'lucide-sprite.svg');
const OUT_LICENSE = path.join(ROOT, 'public', 'vendor', 'lucide', 'LICENSE');
const checkOnly = process.argv.includes('--check');

const names = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
if (!Array.isArray(names) || !names.length) throw new Error('scripts/lucide-icons.json 必须是非空数组');
if (new Set(names).size !== names.length) throw new Error('scripts/lucide-icons.json 存在重复图标名');

const pkg = JSON.parse(fs.readFileSync(path.join(SRC_DIR, 'package.json'), 'utf8'));
const version = pkg.version;

function readIcon(name) {
  const file = path.join(SRC_DIR, 'icons', `${name}.svg`);
  if (!fs.existsSync(file)) throw new Error(`lucide-static 没有图标：${name}`);
  const raw = fs.readFileSync(file, 'utf8');
  const open = raw.match(/<svg[^>]*>/);
  if (!open) throw new Error(`图标缺少 <svg>：${name}`);
  const body = raw
    .slice(open.index + open[0].length, raw.lastIndexOf('</svg>'))
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*\n\s*/g, ' ')
    .replace(/\s{2,}/g, ' ')
    .trim();
  if (!body) throw new Error(`图标内容为空：${name}`);
  return body;
}

const symbols = names
  .map((name) => `  <symbol id="${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">${readIcon(name)}</symbol>`)
  .join('\n');

const sprite = `<!-- Generated by scripts/build-icons.mjs from lucide-static ${version} (ISC). Do not edit by hand. -->
<svg xmlns="http://www.w3.org/2000/svg">
${symbols}
</svg>
`;

const license = fs.readFileSync(path.join(SRC_DIR, 'LICENSE'), 'utf8');

function same(file, content) {
  return fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content;
}

function referenceErrors() {
  const iconNames = new Set(names);
  const errors = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== 'vendor' && entry.name !== 'uploads') walk(full);
        continue;
      }
      if (!/\.(?:js|html)$/.test(entry.name)) continue;
      const text = fs.readFileSync(full, 'utf8');
      for (const m of text.matchAll(/icon\(\s*['"]([a-z0-9-]+)['"]/g)) {
        if (!iconNames.has(m[1])) errors.push(`${path.relative(ROOT, full)}: icon('${m[1]}') 不在清单中`);
      }
      for (const m of text.matchAll(/lucide-sprite\.svg(?:\?v=\d+)?#([a-z0-9-]+)/g)) {
        if (!iconNames.has(m[1])) errors.push(`${path.relative(ROOT, full)}: sprite #${m[1]} 不在清单中`);
      }
    }
  };
  walk(path.join(ROOT, 'public'));
  return errors;
}

const refErrors = referenceErrors();
if (refErrors.length) {
  console.error('图标引用校验失败：');
  refErrors.forEach((e) => console.error('  - ' + e));
  process.exit(1);
}

if (checkOnly) {
  const ok = same(OUT_SPRITE, sprite) && same(OUT_LICENSE, license);
  if (!ok) {
    console.error('图标产物已漂移：请运行 npm run icons 后提交 public/vendor/lucide-sprite.svg 与 LICENSE。');
    process.exit(1);
  }
  console.log(`Lucide sprite 已是最新（lucide-static ${version}，${names.length} 个图标）。`);
} else {
  fs.mkdirSync(path.dirname(OUT_LICENSE), { recursive: true });
  fs.writeFileSync(OUT_SPRITE, sprite);
  fs.writeFileSync(OUT_LICENSE, license);
  console.log(`已生成 ${path.relative(ROOT, OUT_SPRITE)}（lucide-static ${version}，${names.length} 个图标）。`);
}
